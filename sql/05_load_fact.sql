    s.actual_shipping_days,
    s.scheduled_shipping_days,
    s.market,
    s.order_region,
    s.order_country,
    s.order_state,
    s.order_city
FROM staging.stg_dataco_supply_chain AS s
LEFT JOIN warehouse.dim_shipping AS sh
    ON s.shipping_mode = sh.shipping_mode
ON CONFLICT (order_item_id) DO NOTHING;