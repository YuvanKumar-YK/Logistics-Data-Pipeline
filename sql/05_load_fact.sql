    s.order_item_id,
    s.order_id,
    s.customer_id,
    s.product_id,
    TO_CHAR(s.order_date::DATE, 'YYYYMMDD')::INTEGER,
    TO_CHAR(s.shipping_date::DATE, 'YYYYMMDD')::INTEGER,
